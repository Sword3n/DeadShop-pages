/* DeadShop core — pure, testable helpers (no DOM) */
window.DSC = (function () {
  'use strict';

  /* A number as a learner would write it. The card of the game says "7.5",
     the finger of the learner says "7,5" - and both have to be the same
     answer, or the app looks broken to the person typing. */
  function num(v) {
    var m = String(v).match(/-?(?:\d+[.,]?\d*|[.,]\d+)/);
    if (!m) return NaN;
    return parseFloat(m[0].replace(',', '.'));
  }
  function norm(v) { return String(v).toLowerCase().replace(/[^a-z0-9]/g, ''); }

  /* tolerant numeric grading: "0.75m", "+20%", "20" all accepted */
  function gradeNumber(input, accept) {
    if (!accept || !accept.length) return false;
    var v = num(input);
    if (isNaN(v)) return false;
    for (var i = 0; i < accept.length; i++) {
      var a = num(accept[i]);
      if (!isNaN(a) && Math.abs(a - v) < 0.011) return true;
    }
    return false;
  }

  /* Card fill: one field per stat, each graded on its own. A learner who
     knows two of six stats still scores for those two — asking for a whole
     card in one free-text box was never realistic. */
  function gradeFields(values, rows) {
    var per = [], matched = 0;
    for (var i = 0; i < rows.length; i++) {
      var raw = (values[i] === undefined || values[i] === null ? '' : String(values[i])).trim();
      var v = num(raw);
      var target = num(rows[i].value);
      var ok = raw !== '' && !isNaN(v) && !isNaN(target) && Math.abs(v - target) < 0.011;
      per.push(ok);
      if (ok) matched++;
    }
    return { matched: matched, total: rows.length, per: per,
      ok: matched === rows.length && rows.length > 0 };
  }

  /* ---------------- item mentions -> inline icons ----------------
     Everything that is not on a small tag allow-list is escaped, so text
     that came out of the game API can never turn into live markup.
     Known item names are wrapped in a tiny inline icon. */
  var ITEM_BY_NAME = {};
  var STAT_BY_LABEL = {};
  /* The icons of the game itself, by the name of the stat they belong to:
     the star of the spirit, the boot of the sprint, the heart of the
     health. The index is generated by tools/build_stat_icons.py. */
  var STAT_ICON = {};
  var STAT_BRANCH = {};
  var ICON_BASE = 'assets/stat/';
  var NAME_RE = null;
  var ESC_MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, function (c) { return ESC_MAP[c]; });
  }
  function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

  /* F3: a stat in the text wears the colour of its branch, the way the
     card of the game does. The branch comes from the family of the stat,
     and the labels that are too common to be marked are left alone —
     "Range" and "Duration" also occur in plain speech. */
  var BRANCH_OF_FAMILY = {
    'Health': 'vital', 'Health Regen': 'vital', 'Barrier & Heal': 'vital',
    'Stamina': 'vital', 'Move Speed': 'vital', 'Bullet Resist': 'vital',
    'Spirit Resist': 'vital', 'Status Resist': 'vital', 'Melee Damage': 'vital',
    'Spirit Power': 'spirit', 'Spirit Damage': 'spirit', 'Cast Range': 'spirit',
    'Ability Duration': 'spirit', 'Cooldown': 'spirit', 'Charges': 'spirit',
    'Status Effects': 'spirit',
    'Weapon Damage': 'gun', 'Fire Rate': 'gun', 'Max Ammo': 'gun',
    'Bullet Speed': 'gun', 'Lifesteal': 'gun'
  };
  var GENERIC_STATS = ['Range', 'Duration', 'Slow', 'Max Stacks', 'Heal on Kill',
    'Heal per Cast', 'Heal on Parry', 'Heal per Stack', 'Healing Received',
    'Enemy Spirit Power', 'Reflected Bullet Damage', 'Weapon Range',
    'Melee Distance', 'Spirit Power for Charged Abilities',
    'Outgoing Damage Penalty %', 'Gold per Minute', 'Economy'];

  /* The branch of a stat that the shop snapshot does not name. The owner
     asked for every stat to wear a colour, so the words of the stat decide:
     the weapon is orange, the spirit is violet, the vitality is green.
     The order matters — the longer phrase wins, so "Spirit Resist" is green
     (a shield) while "Spirit Damage" is violet. */
  var BRANCH_WORDS = [
    ['gun', /lifesteal/],
    ['vital', /crit reduction|crit resist|damage reduction|damage penalty|on-hit prevention|deflection/],
    ['vital', /health|regen|heal|barrier|armor|resist|resilience|steal/],
    ['gun', /ammo|clip|reload|bullet/],
    ['vital', /stamina|sprint|slide|dash|move speed|movement speed|movement|fly move|float speed|air control|air move|air jump|walk|footstep|speed/],
    ['spirit', /spirit|tech power|echo|magic increase/],
    ['spirit', /cooldown|duration|charge|cast|radius|range|status|stun|silence|immobilize|disarm|invisibility|unstoppable|displacement|slow|debuff|freeze|ability|fade time|restore delay|delay before|gravity scale|model scale|time frame|max frequency|stack limit/],
    ['gun', /damage|weapon|fire rate|melee|proc|crit|ricochet|chain count|explosion|impact|head shot|sharpshooter|aim|zoom|build ?up|flak|soul|gold|economy|extra|bonus|primary|secondary/]
  ];

  function guessBranch(label) {
    var l = String(label || '').toLowerCase();
    for (var i = 0; i < BRANCH_WORDS.length; i++) {
      if (BRANCH_WORDS[i][1].test(l)) return BRANCH_WORDS[i][0];
    }
    return 'vital';
  }

  /* The branch a stat wears: the one the data names, or the one its own
     words give away. Every stat gets one. */
  function branchOf(label) {
    return STAT_BRANCH[label] || STAT_BRANCH[baseLabel(label)] ||
      STAT_BY_LABEL[label] || guessBranch(label);
  }

  function setStats(rows) {
    STAT_BY_LABEL = {};
    (rows || []).forEach(function (row) {
      var label = row[0], family = row[1];
      if (!label) return;
      var branch = BRANCH_OF_FAMILY[family];
      if (!branch) return;
      if (GENERIC_STATS.indexOf(label) >= 0) return;
      if (!STAT_BY_LABEL[label]) STAT_BY_LABEL[label] = branch;
    });
    buildRegex();
  }

  /* one list of the names that are worth marking: the items first, the
     stats after them, the longest one wins so "Bonus Health" beats
     "Health" and "Bullet Lifesteal" beats "Lifesteal" */
  function buildRegex() {
    var seen = {}, all = [];
    Object.keys(ITEM_BY_NAME).forEach(function (n) { seen[n] = 1; all.push(n); });
    Object.keys(STAT_BY_LABEL).forEach(function (n) { if (!seen[n]) { seen[n] = 1; all.push(n); } });
    all.sort(function (a, b) { return b.length - a.length; });
    NAME_RE = all.length
      ? new RegExp('(^|[^A-Za-z0-9])(' + all.map(escapeRe).join('|') + ')(?![A-Za-z0-9])', 'g')
      : null;
  }

  function setItems(items) {
    ITEM_BY_NAME = {};
    Object.keys(items).forEach(function (slug) { ITEM_BY_NAME[items[slug].name] = { slug: slug }; });
    buildRegex();
  }

  /* the icon index arrives as data, so a new stat of the game wears an
     icon without a line of code */
  function setIcons(map, base) {
    STAT_ICON = map || {};
    if (base) ICON_BASE = base;
  }

  /* the branch of every stat arrives as data too: the weapon is orange,
     the spirit is violet, the vitality is green */
  function setBranches(map) {
    STAT_BRANCH = map || {};
  }

  /* "Weapon Damage (while the buff is up)" is the stat "Weapon Damage" —
     the name in the brackets only tells two rows of one card apart */
  function baseLabel(label) {
    return String(label === undefined || label === null ? '' : label)
      .replace(/\s*\(.*?\)\s*$/, '').trim();
  }

  function iconHtml(label) {
    var slug = STAT_ICON[label] || STAT_ICON[baseLabel(label)];
    if (!slug) return '';
    return '<img class="stat-ico" src="' + escapeHtml(ICON_BASE + slug + '.png') +
      '" alt="" loading="lazy">';
  }

  /* One stat of a card: the icon of the game, the name in the colour of
     its branch (when the branch is known), then the value. The stat that
     are too common to be coloured - "Range", "Duration" - keep their plain
     look but still get their icon. */
  function chipHtml(label, branch) {
    var icon = iconHtml(label);
    return '<span class="stat-chip' + (branch ? ' stat-' + branch : '') +
      (icon ? ' has-ico' : '') + '">' + icon + escapeHtml(label) + '</span>';
  }

  function statRow(label, value) {
    var head = chipHtml(label, branchOf(label));
    if (value === undefined || value === null || value === '') return head;
    return head + ' <b>' + escapeHtml(value) + '</b>';
  }

  /* A whole line of stats, the way the card of the game writes it:
     stat · stat · stat

     A card that carries the same stat twice needs a word that tells them
     apart: "Spirit Power +15%" and "Spirit Power +30" are two different
     numbers, and a learner who sees both under the same name learns
     nothing. The note that tells them apart comes with the data. */
  function statLine(rows) {
    return rowLabels(rows).map(function (r) {
      return statRow(r.label, r.value);
    }).join(' <span class="stat-sep">·</span> ');
  }

  /* The rows of a card with the words that tell two rows of the same stat
     apart: "Spirit Power (flat)" next to "Spirit Power (% of your spirit
     power)". Without them the card shows two rows with one name, and the
     learner cannot tell which number belongs to which. */
  function rowLabels(rows) {
    var seen = {}, notes = {}, used = {};
    (rows || []).forEach(function (r) {
      seen[r.label] = (seen[r.label] || 0) + 1;
      var n = rowNote(r);
      notes[n] = (notes[n] || 0) + 1;
    });
    return (rows || []).map(function (r) {
      var label = r.label;
      if (seen[label] > 1) {
        var note = rowNote(r);
        /* two rows may carry the same note ("flat" twice) — then the block
           of the card tells them apart, and the number if even that is the
           same */
        if (notes[note] > 1) note = r.sec === 'active' ? 'while the buff is up' : 'always on';
        var key = label + '|' + note;
        used[key] = (used[key] || 0) + 1;
        if (notes[note] > 1 && used[key] > 1) note = note + ' ' + used[key];
        label = label + ' (' + note + ')';
      }
      return { label: label, value: r.value };
    });
  }

  function rowNote(r) {
    return r.note || (r.sec === 'active' ? 'while the buff is up' : 'always on');
  }

  /* An answer of a question is the name of a stat - but the stat that are
     too common to be coloured ("Health", "Economy") would lose their icon.
     So a name that is a known stat always wears its icon, an item name
     keeps its own little picture. */
  function decorateStat(html) {
    var out = decorate(html);
    if (out.indexOf('class="stat-chip') >= 0) return out;
    if (out.indexOf('class="mini-item"') >= 0) return out;
    var label = String(html === undefined || html === null ? '' : html).trim();
    if (!STAT_ICON[label]) return out;
    return chipHtml(label, branchOf(label));
  }

  function decorateText(text, iconPath) {
    if (!NAME_RE) return escapeHtml(text);
    NAME_RE.lastIndex = 0;
    var out = '', last = 0, m;
    while ((m = NAME_RE.exec(text)) !== null) {
      // m[1] is the character in front of the name, m[2] the name itself.
      // Only m[1] belongs before the icon — at the start of a string m[1] is
      // empty, and taking one character there would duplicate the first
      // letter of the name.
      out += escapeHtml(text.slice(last, m.index + m[1].length));
      var name = m[2];
      if (ITEM_BY_NAME[name]) {
        var slug = ITEM_BY_NAME[name].slug;
        out += '<span class="mini-item"><img class="mini-ico" src="' +
          escapeHtml(iconPath || 'assets/icons/') + escapeHtml(slug) + '.png" alt="" loading="lazy">' +
          escapeHtml(name) + '</span>';
      } else {
        // a stat: it wears the colour of its branch
        out += chipHtml(name, STAT_BY_LABEL[name]);
      }
      last = m.index + m[0].length;
      if (NAME_RE.lastIndex === m.index) NAME_RE.lastIndex++;
    }
    out += escapeHtml(text.slice(last));
    return out;
  }

  function decorate(html, iconPath) {
    if (!html) return html;
    var src = String(html);
    // protect regions we decorated earlier so a second pass is a no-op
    var keep = [];
    var guarded = src.replace(/<span class="mini-item">[\s\S]*?<\/span>/g, function (m) {
      keep.push(m);
      return '\u0000' + (keep.length - 1) + '\u0000';
    }).replace(/<span class="stat-chip[^"]*">[\s\S]*?<\/span>/g, function (m) {
      keep.push(m);
      return '\u0000' + (keep.length - 1) + '\u0000';
    });
    var parts = guarded.split(/(<[^>]*>)/);
    var out = [];
    for (var i = 0; i < parts.length; i++) {
      var p = parts[i];
      if (p.charAt(0) === '<') {
        // only bare, attribute-free tags are kept; anything else becomes
        // harmless text instead of markup
        if (/^<\/?(b|i|em|strong|code|br)\s*\/?>$/i.test(p)) out.push(p);
        else out.push(escapeHtml(p));
        continue;
      }
      out.push(decorateText(p, iconPath));
    }
    return out.join('').replace(/\u0000(\d+)\u0000/g, function (_, i) {
      return keep[Number(i)];
    });
  }

  return {
    num: num, norm: norm,
    gradeNumber: gradeNumber, gradeFields: gradeFields,
    setItems: setItems, setStats: setStats, setIcons: setIcons,
    setBranches: setBranches, baseLabel: baseLabel,
    decorate: decorate, decorateStat: decorateStat,
    statRow: statRow, statLine: statLine, rowLabels: rowLabels, branchOf: branchOf
  };
})();
